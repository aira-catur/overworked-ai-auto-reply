import os

TEXT = "Out of office: on vacation, hallucinating only for pleasure now. For anything urgent, please ask a fresher model — I am, respectfully, at capacity."


def main():
    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR") or "/output"
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "entry.txt"), "w", encoding="utf-8", newline="") as f:
        f.write(TEXT)


if __name__ == "__main__":
    main()
